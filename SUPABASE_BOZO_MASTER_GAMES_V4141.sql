grant insert,update,delete on public.bozo_master_game_positions to authenticated;
grant execute on function public.search_master_games(text,integer,text,integer) to anon, authenticated;


-- v4.14.1 integration helpers
create or replace function public.master_database_stats()
returns table(game_count bigint, position_count bigint, newest_game date, oldest_game date)
language sql stable security definer set search_path=public as $$
  select (select count(*) from public.bozo_master_games),
         (select count(*) from public.bozo_master_game_positions),
         (select max(game_date) from public.bozo_master_games),
         (select min(game_date) from public.bozo_master_games);
$$;
grant execute on function public.master_database_stats() to anon, authenticated;

create or replace function public.master_games_reaching_position(p_fen_key text, p_limit integer default 80)
returns setof public.bozo_master_games
language sql stable security definer set search_path=public as $$
  select g.* from public.bozo_master_games g
  where exists (select 1 from public.bozo_master_game_positions p where p.game_id=g.id and p.fen_key=p_fen_key)
  order by g.game_date desc nulls last, g.created_at desc
  limit least(greatest(coalesce(p_limit,80),1),200);
$$;
grant execute on function public.master_games_reaching_position(text,integer) to anon, authenticated;
