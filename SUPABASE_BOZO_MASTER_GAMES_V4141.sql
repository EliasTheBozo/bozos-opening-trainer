-- BOZO v4.14.0 — Master Games study/training foundation
-- Run once in the Supabase SQL editor.

create extension if not exists pgcrypto;

create table if not exists public.bozo_master_games (
  id uuid primary key default gen_random_uuid(),
  game_key text not null unique,
  white text not null,
  black text not null,
  white_elo integer,
  black_elo integer,
  event text,
  site text,
  game_date date,
  game_year integer,
  round text,
  result text not null default '*',
  eco text,
  opening text,
  starting_fen text not null default 'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1',
  moves_san jsonb not null default '[]'::jsonb,
  moves_uci jsonb not null default '[]'::jsonb,
  move_count integer not null default 0,
  pgn text not null,
  source_label text not null default 'Public PGN',
  imported_by uuid references auth.users(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists bozo_master_games_white_idx on public.bozo_master_games (lower(white));
create index if not exists bozo_master_games_black_idx on public.bozo_master_games (lower(black));
create index if not exists bozo_master_games_year_idx on public.bozo_master_games (game_year desc);
create index if not exists bozo_master_games_eco_idx on public.bozo_master_games (eco);
create index if not exists bozo_master_games_result_idx on public.bozo_master_games (result);

create table if not exists public.bozo_master_game_positions (
  id bigint generated by default as identity primary key,
  game_id uuid not null references public.bozo_master_games(id) on delete cascade,
  ply integer not null,
  fen text not null,
  fen_key text not null,
  san text not null,
  uci text not null,
  unique(game_id, ply)
);
create index if not exists bozo_master_positions_game_idx on public.bozo_master_game_positions(game_id, ply);
create index if not exists bozo_master_positions_fen_key_idx on public.bozo_master_game_positions(fen_key);

create table if not exists public.bozo_master_training_runs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  game_id uuid not null references public.bozo_master_games(id) on delete cascade,
  training_side text not null check (training_side in ('white','black','both')),
  master_matches integer not null default 0,
  alternative_moves integer not null default 0,
  total_decisions integer not null default 0,
  match_percent integer not null default 0,
  decisions jsonb not null default '[]'::jsonb,
  started_at timestamptz,
  completed_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create index if not exists bozo_master_training_user_idx on public.bozo_master_training_runs(user_id, created_at desc);
create index if not exists bozo_master_training_game_idx on public.bozo_master_training_runs(game_id, created_at desc);

alter table public.bozo_master_games enable row level security;
alter table public.bozo_master_game_positions enable row level security;
alter table public.bozo_master_training_runs enable row level security;

